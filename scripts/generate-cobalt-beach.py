#!/usr/bin/env python3
"""Generate the deterministic custom-model beach used by the Cobalt blue demo."""

from __future__ import annotations

import math
import random
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "modules/modelling/src/contentTesting/resources/assets/kasuga_demo/models/cobalt"
TEXTURE_DIR = ROOT / "modules/modelling/src/contentTesting/resources/assets/kasuga_demo/textures/cobalt"

X_MIN, X_MAX, X_STEP = -48.0, 48.0, 1.0
Z_MIN, Z_MAX, Z_STEP = -36.0, 240.0, 0.5
TEXTURE_SIZE = 1024
SEA_LEVEL = 64.55
DEEP_SEABED = -32.0
SHALLOW_SHELF_END = 18.0
DEEP_SLOPE = 0.55


def smoothstep(value: float) -> float:
    value = min(1.0, max(0.0, value))
    return value * value * (3.0 - 2.0 * value)


def shore_z(x: float) -> float:
    """Irregular +Z shoreline used by both the visual mesh and collision layout."""
    return (5.0
            + 1.80 * math.sin(x * 0.21)
            + 0.72 * math.sin(x * 0.57 + 1.1)
            + 0.52 * math.sin(x * 1.31 - 0.4))


def waterline_z(x: float) -> float:
    low, high = shore_z(x), shore_z(x) + 16.0
    for _ in range(48):
        middle = (low + high) * 0.5
        if height(x, middle) > SEA_LEVEL:
            low = middle
        else:
            high = middle
    return (low + high) * 0.5


def height(x: float, z: float) -> float:
    """World-space sand top shared by the OBJ, collision, and waterline."""
    delta = z - shore_z(x)
    ripple = 0.018 * math.sin(x * 0.43 + z * 0.31) + 0.012 * math.sin(x * 1.7 - z * 0.19)
    if delta <= 0:
        # Gentle bank behind the player, still below the blocker plane near the room.
        dune = 1.05 * smoothstep((-delta - 8.0) / 28.0)
        dune *= 0.72 + 0.28 * math.sin(x * 0.19 + 0.8)
        return 64.98 + dune + ripple
    shallow_floor = (64.98 - 0.88 * smoothstep(delta / 3.2)
                     - 0.55 * smoothstep((delta - 3.2) / 7.0))
    if delta <= 10.2:
        return shallow_floor + ripple
    if delta <= SHALLOW_SHELF_END:
        return 63.55 + ripple

    descent = delta - SHALLOW_SHELF_END
    if descent <= 4.0:
        t = descent / 4.0
        drop = DEEP_SLOPE * 4.0 * (t**3 - 0.5 * t**4)
    else:
        drop = DEEP_SLOPE * (descent - 2.0)
    return max(DEEP_SEABED, 63.55 - drop) + ripple


def normal(x: float, z: float) -> tuple[float, float, float]:
    epsilon = 0.02
    dx = (height(x + epsilon, z) - height(x - epsilon, z)) / (2.0 * epsilon)
    dz = (height(x, z + epsilon) - height(x, z - epsilon)) / (2.0 * epsilon)
    length = math.sqrt(dx * dx + 1.0 + dz * dz)
    return (-dx / length, 1.0 / length, -dz / length)


def write_obj() -> None:
    xs = [X_MIN + i * X_STEP for i in range(int((X_MAX - X_MIN) / X_STEP) + 1)]
    zs = [Z_MIN + i * Z_STEP for i in range(int((Z_MAX - Z_MIN) / Z_STEP) + 1)]
    lines = [
        "# Cobalt blue overall beach / custom-model coast",
        "# Minecraft canonical axes: +Y up, player forward +Z, ocean +Z, beach -Z",
        "# Generated by scripts/generate-cobalt-beach.py; do not hand-edit.",
        "mtllib beach.mtl",
        "usemtl coast",
    ]
    for x in xs[::max(1, len(xs) // 13)]:
        lines.append(f"# kasuga_shore_profile {x:.6f} {shore_z(x):.6f}")
        line = waterline_z(x)
        lines.append(f"# kasuga_waterline_profile {x:.6f} {line:.6f} {height(x, line):.6f}")
    for z in zs:
        for x in xs:
            lines.append(f"v {x:.6f} {height(x, z):.6f} {z:.6f}")
    for z in zs:
        for x in xs:
            lines.append(f"vt {(x - X_MIN) / (X_MAX - X_MIN):.6f} "
                         f"{1.0 - (z - Z_MIN) / (Z_MAX - Z_MIN):.6f}")
    for z in zs:
        for x in xs:
            nx, ny, nz = normal(x, z)
            lines.append(f"vn {nx:.7f} {ny:.7f} {nz:.7f}")

    width = len(xs)
    face_count = 0
    for row, z0 in enumerate(zs[:-1]):
        z1 = zs[row + 1]
        for column, x0 in enumerate(xs[:-1]):
            x1 = xs[column + 1]
            a = row * width + column + 1
            b = (row + 1) * width + column + 1
            c = b + 1
            d = a + 1
            # Counter-clockwise from above: +Z edge x +X edge => +Y normal.
            lines.append(f"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c} {d}/{d}/{d}")
            face_count += 1
    if face_count == 0:
        raise RuntimeError("beach OBJ produced no faces")

    target = ASSET_DIR / "beach.obj"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}: {len(xs) * len(zs)} vertices, {face_count} quads")


def write_mtl() -> None:
    lines = [
        "# Generated cobalt beach material",
        "newmtl coast",
        "Kd 1.0 1.0 1.0",
        "Ke 0.0 0.0 0.0",
        "Ks 0.02 0.025 0.03",
        "Ns 8.0",
        "Pr 0.92",
        "d 1.0",
        "map_Kd kasuga_demo:cobalt/coast",
        "",
    ]
    target = ASSET_DIR / "beach.mtl"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")


def write_textures() -> None:
    rng = random.Random(0xC0BA17)
    image = Image.new("RGB", (TEXTURE_SIZE, TEXTURE_SIZE))
    pixels = image.load()
    dry = (198.0, 190.0, 170.0)
    wet = (132.0, 137.0, 128.0)
    shallow = (151.0, 157.0, 145.0)
    deep = (105.0, 123.0, 122.0)
    shoreline = [shore_z(X_MIN + (x + 0.5) / TEXTURE_SIZE * (X_MAX - X_MIN))
                 for x in range(TEXTURE_SIZE)]
    waterline = [waterline_z(X_MIN + (x + 0.5) / TEXTURE_SIZE * (X_MAX - X_MIN))
                 for x in range(TEXTURE_SIZE)]
    for y in range(TEXTURE_SIZE):
        world_z = Z_MIN + (y + 0.5) / TEXTURE_SIZE * (Z_MAX - Z_MIN)
        for x in range(TEXTURE_SIZE):
            delta = world_z - shoreline[x]
            water_delta = waterline[x] - shoreline[x]
            if delta <= -0.8:
                color = dry
            elif delta < water_delta:
                color = tuple(dry[i] + (wet[i] - dry[i]) * smoothstep((delta + 0.8) / (water_delta + 0.8))
                              for i in range(3))
            elif delta < water_delta + 7.0:
                color = tuple(wet[i] + (shallow[i] - wet[i]) * smoothstep((delta - water_delta) / 7.0)
                              for i in range(3))
            else:
                color = tuple(shallow[i] + (deep[i] - shallow[i]) * smoothstep((delta - water_delta - 7.0) / 18.0)
                              for i in range(3))
            grain = rng.randint(-9, 9)
            ripple = 3.0 * math.sin(x * 0.075 + y * 0.043) + 2.0 * math.sin(x * 0.19 - y * 0.071)
            pixels[x, y] = tuple(
                max(0, min(255, int(channel + grain + ripple)))
                for channel in color
            )
    target = TEXTURE_DIR / "coast.png"
    image.save(target, optimize=True)
    print(f"wrote deterministic coast texture {target.relative_to(ROOT)}")


def validate() -> None:
    with Image.open(TEXTURE_DIR / "coast.png") as image:
        if image.size != (TEXTURE_SIZE, TEXTURE_SIZE) or image.mode != "RGB":
            raise RuntimeError(f"coast.png must be a {TEXTURE_SIZE}x{TEXTURE_SIZE} RGB image, "
                               f"got {image.mode} {image.size}")
    for x in (X_MIN, -16.0, 0.0, 16.0, X_MAX):
        for z in (0.0, shore_z(x), 12.0):
            if not math.isfinite(height(x, z)):
                raise RuntimeError(f"non-finite beach vertex at {x}, {z}")
        line = waterline_z(x)
        if abs(height(x, line) - SEA_LEVEL) > 1e-5:
            raise RuntimeError(f"waterline mismatch at x={x}: z={line}, height={height(x, line)}")
    if height(0.0, shore_z(0.0) + 8.0) < SEA_LEVEL - 1.5:
        raise RuntimeError("the near shore must retain a shallow walking shelf")
    if height(0.0, shore_z(0.0) + 220.0) > DEEP_SEABED + 0.1:
        raise RuntimeError("the far seabed must reach the authored deep-ocean floor")
    shoreline = [shore_z(X_MIN + index * 4.0) for index in range(int((X_MAX - X_MIN) / 4.0) + 1)]
    if max(shoreline) - min(shoreline) < 3.0:
        raise RuntimeError(f"shoreline is not irregular enough: {shoreline}")


def main() -> None:
    ASSET_DIR.mkdir(parents=True, exist_ok=True)
    TEXTURE_DIR.mkdir(parents=True, exist_ok=True)
    write_textures()
    write_mtl()
    write_obj()
    validate()


if __name__ == "__main__":
    main()
